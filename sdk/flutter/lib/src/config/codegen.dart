import 'dart:convert';

import 'parameter_schema.dart';

/// Normalized declarations for the server. Uses the YAML keys, so the
/// generator can read it back as the previous version.
String generateParameterSchemaJson(ParameterSchema schema) =>
    '${const JsonEncoder.withIndent('  ').convert(schema.toJson())}\n';

/// Typed Dart config code: one getter per parameter, one enum per enum parameter.
/// Throws ParameterSchemaException when a name cannot become Dart code.
String generateConfigDart(
  ParameterSchema schema, {
  required String className,
  required String sourceName,
}) {
  final clashes = [
    for (final p in schema.parameters)
      if (p.type == ParameterType.enumeration && _enumName(p) == className)
        'parameters.${p.name}: its enum would be named $className, like the generated class',
  ];
  if (clashes.isNotEmpty) throw ParameterSchemaException(clashes);

  final out = StringBuffer()
    ..writeln('// GENERATED by the renvix_sdk config generator from $sourceName.')
    ..writeln('// Do not edit by hand: change the parameters and run the generator.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'package:renvix_sdk/renvix_sdk.dart';")
    ..writeln();

  for (final p in schema.parameters) {
    if (p.type != ParameterType.enumeration) continue;
    final enumName = _enumName(p);
    if (p.description case final description?) _doc(out, description, '');
    out
      ..writeln('enum $enumName {')
      ..writeln('${p.values.map((v) => "  ${_identifier(_camel(v))}('$v')").join(',\n')};')
      ..writeln()
      ..writeln('  const $enumName(this.wireName);')
      ..writeln()
      ..writeln('  final String wireName;')
      ..writeln('}')
      ..writeln();
  }

  out
    ..writeln('/// Typed remote config parameters from $sourceName.')
    ..writeln('///')
    ..writeln('/// Every getter returns the value for this user, or the built-in default')
    ..writeln('/// when there is none or this app version cannot use it.')
    ..writeln('class $className {')
    ..writeln('  const $className(this._source);')
    ..writeln()
    ..writeln('  final ConfigSource _source;');

  for (final p in schema.parameters) {
    final getter = _identifier(_camel(p.name));
    final key = "'${p.name}'";

    out.writeln();
    if (p.description case final description?) _doc(out, description, '  ');
    if (p.deprecated) out.writeln("  @Deprecated('Deprecated in the parameter schema')");

    switch (p.type) {
      case ParameterType.boolean:
        out.writeln('  bool get $getter => _source.readBool($key, defaultValue: ${p.defaultValue});');
      case ParameterType.integer:
        out.writeln(
          '  int get $getter => _source.readInt($key, defaultValue: ${p.defaultValue}${_bounds(p, _int)});',
        );
      case ParameterType.number:
        out.writeln(
          '  double get $getter => _source.readNumber($key, '
          'defaultValue: ${_double(p.defaultValue as num)}${_bounds(p, _double)});',
        );
      case ParameterType.string:
        out.writeln(
          '  String get $getter => _source.readString($key, '
          'defaultValue: ${_dartString(p.defaultValue as String)}, maxLength: ${p.maxLength});',
        );
      case ParameterType.enumeration:
        final enumName = _enumName(p);
        final wire = p.defaultValue as String;
        final values = p.values.map((v) => "'$v'").join(', ');
        out
          ..writeln('  $enumName get $getter {')
          ..writeln("    final wire = _source.readEnum($key, defaultValue: '$wire', values: const [$values]);")
          ..writeln('    return $enumName.values.firstWhere(')
          ..writeln('      (v) => v.wireName == wire,')
          ..writeln('      orElse: () => $enumName.${_identifier(_camel(wire))},')
          ..writeln('    );')
          ..writeln('  }');
    }
  }

  out.writeln('}');
  return out.toString();
}

String _int(num value) => '$value';

String _double(num value) => value is int ? '$value.0' : '$value';

String _bounds(ParameterDefinition p, String Function(num) format) => [
      if (p.min case final min?) ', min: ${format(min)}',
      if (p.max case final max?) ', max: ${format(max)}',
    ].join();

// A single-quoted Dart literal: quotes, backslashes, $ and line breaks escaped
String _dartString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return "'$escaped'";
}

// Types from dart:core an enum must not shadow
const _coreTypes = {
  'bool', 'Comparable', 'DateTime', 'double', 'Duration', 'Enum', 'Error',
  'Exception', 'Function', 'Future', 'int', 'Iterable', 'List', 'Map', 'Never',
  'Null', 'num', 'Object', 'Pattern', 'Record', 'RegExp', 'Set', 'Sink',
  'Stream', 'String', 'Symbol', 'Type', 'Uri',
};

String _enumName(ParameterDefinition p) {
  final name = _pascal(p.name);
  return _coreTypes.contains(name) ? '${name}Value' : name;
}

String _camel(String snake) {
  final parts = snake.split('_');
  return parts.first + parts.skip(1).map(_capitalize).join();
}

String _pascal(String snake) => snake.split('_').map(_capitalize).join();

String _capitalize(String part) => part.isEmpty ? part : part[0].toUpperCase() + part.substring(1);

void _doc(StringBuffer out, String text, String indent) {
  for (final line in text.trim().split('\n')) {
    out.writeln('$indent/// ${line.trim()}'.trimRight());
  }
}

// Dart keywords and names already used by enums and Object
const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', 'default',
  'do', 'else', 'enum', 'extends', 'false', 'final', 'finally', 'for', 'if',
  'in', 'is', 'new', 'null', 'rethrow', 'return', 'super', 'switch', 'this',
  'throw', 'true', 'try', 'var', 'void', 'while', 'with',
  'values', 'index', 'name', 'wireName', 'hashCode', 'runtimeType', 'toString',
  'noSuchMethod',
};

String _identifier(String name) => _reserved.contains(name) ? '${name}Value' : name;