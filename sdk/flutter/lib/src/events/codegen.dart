import 'dart:convert';

import 'tracking_plan.dart';

/// Normalized plan for the server. Uses the YAML keys, so the generator can
/// read it back as the previous version of the plan.
String generatePlanJson(TrackingPlan plan) =>
    '${const JsonEncoder.withIndent('  ').convert(plan.toJson())}\n';

/// Typed Dart tracking code: one method per event, one enum per enum property.
String generateDart(
  TrackingPlan plan, {
  required String className,
  required String importDirective,
  required String sourceName,
  String? nameSetConstant,
}) {
  final out = StringBuffer()
    ..writeln('// GENERATED by the renvix_sdk events generator from $sourceName.')
    ..writeln('// Do not edit by hand: change the tracking plan and run the generator.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln(importDirective)
    ..writeln();

  if (nameSetConstant != null) {
    out.writeln('/// Names of all events in this plan');
    out.writeln('const Set<String> $nameSetConstant = {');
    for (final event in plan.events) {
      out.writeln("  '${event.name}',");
    }
    out
      ..writeln('};')
      ..writeln();
  }

  for (final event in plan.events) {
    for (final property in _active(event)) {
      if (property.type != PropertyType.enumeration) continue;
      if (property.description case final description?) _doc(out, description, '');
      out
        ..writeln('enum ${_enumName(event, property)} {')
        ..writeln('${property.values.map((v) => "  ${_identifier(_camel(v))}('$v')").join(',\n')};')        ..writeln()
        ..writeln('  const ${_enumName(event, property)}(this.wireName);')
        ..writeln()
        ..writeln('  final String wireName;')
        ..writeln('}')
        ..writeln();
    }
  }

  out
    ..writeln('/// Typed events from $sourceName.')
    ..writeln('class $className {')
    ..writeln('  const $className(this._tracker);')
    ..writeln()
    ..writeln('  final EventTracker _tracker;');

  for (final event in plan.events) {
    final properties = _active(event);
    final method = _identifier(_camel(event.name));
    final category = 'EventCategory.${event.category.name}';

    out.writeln();
    _doc(out, event.description, '  ');
    final documented = properties.where((p) => p.description != null).toList();
    if (documented.isNotEmpty) {
      out.writeln('  ///');
      for (final p in documented) {
        out.writeln('  /// - [${_identifier(_camel(p.name))}]: ${_oneLine(p.description!)}');
      }
    }
    if (event.deprecated) out.writeln("  @Deprecated('Deprecated in the tracking plan')");

    if (properties.isEmpty) {
      out
        ..writeln('  void $method() {')
        ..writeln("    _tracker.track('${event.name}', $category, const {});")
        ..writeln('  }');
      continue;
    }

    out.writeln('  void $method({');
    for (final p in properties) {
      final type = _dartType(event, p);
      final parameter = _identifier(_camel(p.name));
      out.writeln(p.required ? '    required $type $parameter,' : '    $type? $parameter,');
    }
    out
      ..writeln('  }) {')
      ..writeln("    _tracker.track('${event.name}', $category, {");
    for (final p in properties) {
      final parameter = _identifier(_camel(p.name));
      final value = p.type == PropertyType.enumeration
          ? (p.required ? '$parameter.wireName' : '$parameter?.wireName')
          : parameter;
      // "?" leaves out optional properties that were not passed
      out.writeln("      '${p.name}': ${p.required ? '' : '?'}$value,");
    }
    out
      ..writeln('    });')
      ..writeln('  }');
  }

  out.writeln('}');
  return out.toString();
}

// Deprecated properties are still accepted by the server but no longer sent
List<PropertyDefinition> _active(EventDefinition event) =>
    event.properties.where((p) => !p.deprecated).toList();

String _dartType(EventDefinition event, PropertyDefinition p) => switch (p.type) {
      PropertyType.boolean => 'bool',
      PropertyType.integer => 'int',
      PropertyType.number => 'num',
      PropertyType.string => 'String',
      PropertyType.enumeration => _enumName(event, p),
    };

String _enumName(EventDefinition event, PropertyDefinition p) =>
    '${_pascal(event.name)}${_pascal(p.name)}';

String _camel(String snake) {
  final parts = snake.split('_');
  return parts.first + parts.skip(1).map(_capitalize).join();
}

String _pascal(String snake) => snake.split('_').map(_capitalize).join();

String _capitalize(String part) => part.isEmpty ? part : part[0].toUpperCase() + part.substring(1);

String _oneLine(String text) => text.split('\n').map((l) => l.trim()).where((l) => l.isNotEmpty).join(' ');

void _doc(StringBuffer out, String text, String indent) {
  for (final line in text.trim().split('\n')) {
    out.writeln('$indent/// ${line.trim()}'.trimRight());
  }
}

// Dart keywords and names already used by enums and the generated class
const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', 'default',
  'do', 'else', 'enum', 'extends', 'false', 'final', 'finally', 'for', 'if',
  'in', 'is', 'new', 'null', 'rethrow', 'return', 'super', 'switch', 'this',
  'throw', 'true', 'try', 'var', 'void', 'while', 'with',
  'values', 'index', 'name', 'wireName', 'hashCode', 'runtimeType', 'toString',
};

String _identifier(String name) => _reserved.contains(name) ? '${name}Value' : name;