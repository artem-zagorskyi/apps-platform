import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  foreignKey,
  index,
  integer,
  pgSchema,
  real,
  text,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';
import { createdAt, primaryId, tz } from '../../core/columns.js';
import {
  appPlatforms,
  apps,
  authProviderEnum,
  platformEnum,
} from '../apps/schema.js';

// All tables of this module live in the "identity" Postgres schema
export const identitySchema = pgSchema('identity');

export const userStatusEnum = identitySchema.enum('user_status', [
  'active',
  'merged',
  'deletion_pending',
  'deleted',
]);

// iOS ATT status or Android advertising ID availability
export const adTrackingEnum = identitySchema.enum('ad_tracking_status', [
  'authorized',
  'denied',
  'restricted',
  'not_determined',
  'unavailable',
]);

export const revokeReasonEnum = identitySchema.enum('revoke_reason', [
  'logout',
  'reuse_detected',
  'superseded', // replaced after a retried refresh within the grace window
  'merged',
  'account_deleted',
  'admin',
]);

export const mergeStrategyEnum = identitySchema.enum('merge_strategy', [
  'keep_target', // keep progress of the existing account
  'keep_source', // keep progress from this device
  'merge', // let the app backend combine both
]);

export const consentPurposeEnum = identitySchema.enum('consent_purpose', [
  'ads',
  'analytics',
  'personalization',
]);

export const consentSourceEnum = identitySchema.enum('consent_source', [
  'first_launch',
  'reprompt',
  'settings',
  'consent_or_pay',
]);

// A user of one app. The id never changes.
export const users = identitySchema.table(
  'users',
  {
    id: primaryId(),
    appId: uuid('app_id')
      .notNull()
      .references(() => apps.id),
    status: userStatusEnum('status').notNull().default('active'),
    mergedInto: uuid('merged_into'),
    createdAt: createdAt(),
    deletionRequestedAt: tz('deletion_requested_at'),
    deletionScheduledAt: tz('deletion_scheduled_at'),
    deletedAt: tz('deleted_at'),
  },
  (t) => [
    // Target for composite foreign keys from other tables
    unique('users_id_app_id_key').on(t.id, t.appId),
    // A user can only be merged into a user of the same app
    foreignKey({
      name: 'users_merged_into_fk',
      columns: [t.mergedInto, t.appId],
      foreignColumns: [t.id, t.appId],
    }),
    // merged_into is set exactly when the status is "merged"
    check(
      'users_merged_into_matches_status',
      sql`(${t.status} = 'merged') = (${t.mergedInto} is not null)`,
    ),
    // Lets the deletion job find due users without scanning the whole table
    index('users_deletion_due_idx')
      .on(t.deletionScheduledAt)
      .where(sql`${t.status} = 'deletion_pending'`),
  ],
);

// One installation of the app on one device.
// Device fields hold the last known values and are updated on every launch.
export const installations = identitySchema.table(
  'installations',
  {
    // Generated by the device on first launch
    id: uuid('id').primaryKey(),
    appId: uuid('app_id').notNull(),
    userId: uuid('user_id').notNull(),
    platform: platformEnum('platform').notNull(),

    // Always collected: needed to operate the app
    appVersion: text('app_version').notNull(),
    appBuild: text('app_build').notNull(),
    osVersion: text('os_version').notNull(),

    // Collected only with analytics consent, otherwise null
    deviceManufacturer: text('device_manufacturer'),
    deviceModel: text('device_model'),
    screenWidth: integer('screen_width'),
    screenHeight: integer('screen_height'),
    screenDensity: real('screen_density'),
    ramMb: integer('ram_mb'),
    storageFreeMb: integer('storage_free_mb'),
    locale: text('locale'),
    timezone: text('timezone'),
    installSource: text('install_source'),
    notificationsEnabled: boolean('notifications_enabled'),
    adTracking: adTrackingEnum('ad_tracking').notNull().default('not_determined'),

    // Derived from the IP on the server; the IP itself is never stored
    country: text('country'),
    region: text('region'),
    city: text('city'),
    geoLat: real('geo_lat'), // city center, not the device position
    geoLon: real('geo_lon'),

    createdAt: createdAt(),
    updatedAt: tz('updated_at').notNull().defaultNow(),
    lastSeenAt: tz('last_seen_at').notNull().defaultNow(),
  },
  (t) => [
    // The owner must belong to the same app
    foreignKey({
      name: 'installations_user_fk',
      columns: [t.userId, t.appId],
      foreignColumns: [users.id, users.appId],
    }),
    // The platform must be registered for this app
    foreignKey({
      name: 'installations_app_platform_fk',
      columns: [t.appId, t.platform],
      foreignColumns: [appPlatforms.appId, appPlatforms.platform],
    }),
    index('installations_user_id_idx').on(t.userId),
  ],
);

// A sign-in method linked to a user: Google or Apple account
export const authIdentities = identitySchema.table(
  'auth_identities',
  {
    id: primaryId(),
    appId: uuid('app_id').notNull(),
    userId: uuid('user_id').notNull(),
    provider: authProviderEnum('provider').notNull(),
    // Stable account id issued by the provider ("sub" claim)
    providerSubject: text('provider_subject').notNull(),
    email: text('email'),
    // Copied from the provider token: whether the provider verified the email
    emailVerified: boolean('email_verified').notNull().default(false),
    emailIsPrivateRelay: boolean('email_is_private_relay').notNull().default(false),
    // Encrypted by the server before saving; used to revoke on account deletion
    appleRefreshToken: text('apple_refresh_token'),
    createdAt: createdAt(),
    lastUsedAt: tz('last_used_at').notNull().defaultNow(),
  },
  (t) => [
    foreignKey({
      name: 'auth_identities_user_fk',
      columns: [t.userId, t.appId],
      foreignColumns: [users.id, users.appId],
    }),
    // One provider account belongs to exactly one user per app
    unique('auth_identities_provider_account_key').on(
      t.appId,
      t.provider,
      t.providerSubject,
    ),
    // A user links at most one account per provider
    unique('auth_identities_user_provider_key').on(t.userId, t.provider),
  ],
);

// Refresh token sessions. Rotated on every use, chained by family_id.
export const sessions = identitySchema.table(
  'sessions',
  {
    id: primaryId(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id),
    installationId: uuid('installation_id')
      .notNull()
      .references(() => installations.id),
    // Shared by every token descended from one sign-in
    familyId: uuid('family_id').notNull(),
    // SHA-256 of the refresh token; the token itself is never stored
    tokenHash: text('token_hash').notNull().unique(),
    createdAt: createdAt(),
    expiresAt: tz('expires_at').notNull(),
    rotatedAt: tz('rotated_at'),
    replacedBy: uuid('replaced_by'),
    revokedAt: tz('revoked_at'),
    revokeReason: revokeReasonEnum('revoke_reason'),
  },
  (t) => [
    foreignKey({
      name: 'sessions_replaced_by_fk',
      columns: [t.replacedBy],
      foreignColumns: [t.id],
    }),
    // A revoked session always has a reason, an active one never does
    check(
      'sessions_revoke_consistent',
      sql`(${t.revokedAt} is null) = (${t.revokeReason} is null)`,
    ),
    index('sessions_family_id_idx').on(t.familyId),
    index('sessions_user_id_idx').on(t.userId),
  ],
);

// History of account merges (user B merged into user A)
export const userMerges = identitySchema.table(
  'user_merges',
  {
    id: primaryId(),
    appId: uuid('app_id').notNull(),
    sourceUserId: uuid('source_user_id').notNull(),
    targetUserId: uuid('target_user_id').notNull(),
    installationId: uuid('installation_id')
      .notNull()
      .references(() => installations.id),
    strategy: mergeStrategyEnum('strategy').notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    foreignKey({
      name: 'user_merges_source_fk',
      columns: [t.sourceUserId, t.appId],
      foreignColumns: [users.id, users.appId],
    }),
    foreignKey({
      name: 'user_merges_target_fk',
      columns: [t.targetUserId, t.appId],
      foreignColumns: [users.id, users.appId],
    }),
    // A user can be merged away only once
    unique('user_merges_source_key').on(t.sourceUserId),
    check('user_merges_not_self', sql`${t.sourceUserId} <> ${t.targetUserId}`),
  ],
);

// Append-only consent log. The current state is the latest row per purpose.
export const consents = identitySchema.table(
  'consents',
  {
    id: primaryId(),
    appId: uuid('app_id').notNull(),
    userId: uuid('user_id').notNull(),
    installationId: uuid('installation_id')
      .notNull()
      .references(() => installations.id),
    purpose: consentPurposeEnum('purpose').notNull(),
    granted: boolean('granted').notNull(),
    policyVersion: text('policy_version').notNull(),
    // Which regional rule applied when the choice was made
    region: text('region').notNull(),
    source: consentSourceEnum('source').notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    foreignKey({
      name: 'consents_user_fk',
      columns: [t.userId, t.appId],
      foreignColumns: [users.id, users.appId],
    }),
    // Fast lookup of the latest decision per user and purpose
    index('consents_user_purpose_idx').on(t.userId, t.purpose, t.createdAt.desc()),
  ],
);

// One-time numbers bound to an installation. Google and Apple embed them
// into their ID tokens, so a stolen token cannot be replayed elsewhere.
export const authNonces = identitySchema.table(
  'auth_nonces',
  {
    id: primaryId(),
    installationId: uuid('installation_id')
      .notNull()
      .references(() => installations.id),
    // SHA-256 (hex) of the nonce; the nonce itself is known only to the client.
    // Apple tokens carry exactly this hash, Google tokens carry the raw nonce.
    nonceHash: text('nonce_hash').notNull().unique(),
    createdAt: createdAt(),
    expiresAt: tz('expires_at').notNull(),
    usedAt: tz('used_at'),
  },
  (t) => [index('auth_nonces_installation_id_idx').on(t.installationId)],
);